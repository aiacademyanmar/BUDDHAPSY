CREATE DATABASE IF NOT EXISTS buddha_care CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE buddha_care;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(150) NOT NULL,email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,role ENUM('patient','doctor','admin') NOT NULL DEFAULT 'patient',
 is_active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS consent_records (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,
 consent_type VARCHAR(80) NOT NULL,version VARCHAR(30) NOT NULL,accepted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id),INDEX(user_id,consent_type)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS doctors (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 display_name VARCHAR(150) NOT NULL,specialty VARCHAR(140) NOT NULL,
 license_number VARCHAR(100) NOT NULL,license_issuer VARCHAR(150) NOT NULL,
 verified TINYINT(1) NOT NULL DEFAULT 0,verified_by BIGINT UNSIGNED NULL,verified_at DATETIME NULL,
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(verified_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS appointments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,patient_id BIGINT UNSIGNED NOT NULL,
 doctor_id BIGINT UNSIGNED NOT NULL,starts_at DATETIME NOT NULL,
 modality ENUM('online','in_person') NOT NULL,
 reason VARCHAR(500) NULL,status ENUM('requested','confirmed','cancelled','completed') NOT NULL DEFAULT 'requested',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(patient_id) REFERENCES users(id),FOREIGN KEY(doctor_id) REFERENCES doctors(id),
 INDEX(doctor_id,starts_at),INDEX(patient_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS api_tokens (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE,expires_at DATETIME NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id),INDEX(user_id,expires_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,actor_id BIGINT UNSIGNED NULL,event VARCHAR(100) NOT NULL,
 target_type VARCHAR(60) NULL,target_id BIGINT UNSIGNED NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX(actor_id,created_at)
) ENGINE=InnoDB;
